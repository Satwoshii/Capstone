import 'package:flutter/material.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import 'peripheral_form.dart';

/// QRScanner handles the scanning of PC identification QR codes.
class QRScanner extends StatelessWidget {
  // Keeps track of the current PC being monitored.
  static String? currentPC;

  /// Shows an error dialog if the scanned QR code is invalid.
  void showInvalidQR(BuildContext context) {
    showDialog(
      context: context,
      builder: (_) => const AlertDialog(
        title: Text("Invalid QR"),
        content: Text("This QR code is not generated by the ITSO system."),
      ),
    );
  }

  /// Checks if the scanned PC matches the current monitoring session.
  void checkPC(BuildContext context, String scannedPC) {
    if (currentPC != null && currentPC != scannedPC) {
      showDialog(
        context: context,
        builder: (_) => AlertDialog(
          title: const Text("Switch PC"),
          content: Text("You are already in $currentPC. Switch to $scannedPC?"),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(context),
              child: const Text("No"),
            ),
            TextButton(
              onPressed: () {
                currentPC = scannedPC;
                Navigator.pushReplacement(
                  context,
                  MaterialPageRoute(
                    builder: (_) => PeripheralForm(pcID: scannedPC),
                  ),
                );
              },
              child: const Text("Yes"),
            )
          ],
        ),
      );
    } else {
      currentPC = scannedPC;
      Navigator.pushReplacement(
        context,
        MaterialPageRoute(
          builder: (_) => PeripheralForm(pcID: scannedPC),
        ),
      );
    }
  }

  /// Validates and parses the QR data to extract PC information.
  String? parsePC(String qrData) {
    try {
      Uri uri = Uri.parse(qrData);

      // Only allow your official domain
      if (uri.host != "itso-view.web.app") {
        return null;
      }

      String? lab = uri.queryParameters['lab'];
      String? pc = uri.queryParameters['pc'];

      if (lab != null && pc != null) {
        return "$lab/$pc";
      }
    } catch (_) {}

    return null;
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text("Scan QR"),
      ),
      body: MobileScanner(
        controller: MobileScannerController(
          detectionSpeed: DetectionSpeed.noDuplicates,
        ),
        onDetect: (BarcodeCapture capture) {
          for (final barcode in capture.barcodes) {
            final raw = barcode.rawValue;

            if (raw != null) {
              String? parsedPC = parsePC(raw);

              if (parsedPC != null) {
                checkPC(context, parsedPC);
              } else {
                showInvalidQR(context);
              }
              break;
            }
          }
        },
      ),
    );
  }
}
