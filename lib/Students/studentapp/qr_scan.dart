import 'package:flutter/material.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import 'peripheral_form.dart';

class QRScanner extends StatefulWidget {
  const QRScanner({super.key});

  @override
  State<QRScanner> createState() => _QRScannerState();
}

class _QRScannerState extends State<QRScanner> {

  /// Current monitored PC
  static String? currentPC;

  /// Prevents multiple scans
  bool scanLocked = false;

  /// Validate and parse QR
  String? parsePC(String qrData) {

    try {

      Uri uri = Uri.parse(qrData);

      /// Only accept QR from your system
      if (uri.host != "itso-view.web.app") {
        return null;
      }

      /// Extract unique code
      String? code = uri.queryParameters['code'];

      if (code != null && code.isNotEmpty) {
        return code;
      }

    } catch (_) {}

    return null;
  }

  /// Show invalid QR dialog
  void showInvalidQR() {

    showDialog(
      context: context,
      builder: (_) => AlertDialog(

        title: const Text(
          "Invalid QR",
          style: TextStyle(color: Colors.red),
        ),

        content: const Text(
          "This QR code is not generated by the ITSO system.",
        ),

        actions: [

          TextButton(
            onPressed: () {
              Navigator.pop(context);
              scanLocked = false;
            },
            child: const Text("OK"),
          )

        ],
      ),
    );

  }

  /// Handle PC switching
  void checkPC(String scannedPC) {

    if (currentPC != null && currentPC != scannedPC) {

      showDialog(
        context: context,
        builder: (_) => AlertDialog(

          title: const Text("Switch PC"),

          content: Text(
              "You are already monitoring $currentPC.\n\nSwitch to $scannedPC?"
          ),

          actions: [

            TextButton(
              onPressed: () {
                Navigator.pop(context);
                scanLocked = false;
              },
              child: const Text("No"),
            ),

            TextButton(
              onPressed: () {

                currentPC = scannedPC;

                Navigator.pushReplacement(
                  context,
                  MaterialPageRoute(
                    builder: (_) => PeripheralForm(pcID: scannedPC),
                  ),
                );

              },
              child: const Text("Yes"),
            ),

          ],
        ),
      );

    } else {

      currentPC = scannedPC;

      Navigator.pushReplacement(
        context,
        MaterialPageRoute(
          builder: (_) => PeripheralForm(pcID: scannedPC),
        ),
      );

    }

  }

  @override
  Widget build(BuildContext context) {

    return Scaffold(

      appBar: AppBar(
        title: const Text("Scan QR"),
      ),

      body: Stack(
        children: [

          /// Camera Scanner
          MobileScanner(

            controller: MobileScannerController(
              detectionSpeed: DetectionSpeed.noDuplicates,
            ),

            onDetect: (BarcodeCapture capture) {

              if (scanLocked) return;

              for (final barcode in capture.barcodes) {

                final raw = barcode.rawValue;

                if (raw != null) {

                  scanLocked = true;

                  String? parsedPC = parsePC(raw);

                  if (parsedPC != null) {

                    checkPC(parsedPC);

                  } else {

                    showInvalidQR();

                  }

                  break;
                }

              }

            },

          ),

          /// Scan Box UI Overlay
          Center(
            child: Container(
              width: 260,
              height: 260,
              decoration: BoxDecoration(
                border: Border.all(
                  color: Colors.amber,
                  width: 4,
                ),
              ),
            ),
          ),

        ],
      ),
    );

  }

}